'use strict';
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('launcher', {
  versionsList: () => ipcRenderer.invoke('versions:list'),
  installedVersions: (instanceId) => ipcRenderer.invoke('versions:installed', instanceId),
  offlineLogin: (nick) => ipcRenderer.invoke('account:offline', nick),
  microsoftLogin: () => ipcRenderer.invoke('account:microsoft'),
  epicRegister: (creds) => ipcRenderer.invoke('account:epic-register', creds),
  epicLogin: (creds) => ipcRenderer.invoke('account:epic-login', creds),
  epicTest: () => ipcRenderer.invoke('account:epic-test'),
  getAccount: () => ipcRenderer.invoke('account:get'),
  logout: () => ipcRenderer.invoke('account:logout'),
  launch: (opts) => ipcRenderer.invoke('game:launch', opts),
  killGame: () => ipcRenderer.invoke('game:kill'),
  javaList: () => ipcRenderer.invoke('java:list'),
  downloadJava: (opts) => ipcRenderer.invoke('java:download', opts),
  openGameDir: (instanceId) => ipcRenderer.invoke('paths:open', instanceId),
  gameDir: (instanceId) => ipcRenderer.invoke('paths:gameDir', instanceId),
  instancesList: () => ipcRenderer.invoke('instances:list'),
  instanceGet: (id) => ipcRenderer.invoke('instances:get', id),
  instanceCreate: (o) => ipcRenderer.invoke('instances:create', o),
  instanceUpdate: (o) => ipcRenderer.invoke('instances:update', o),
  instanceDelete: (id) => ipcRenderer.invoke('instances:delete', id),
  instanceDuplicate: (o) => ipcRenderer.invoke('instances:duplicate', o),
  instanceExport: (o) => ipcRenderer.invoke('instances:export', o),
  instanceImport: (o) => ipcRenderer.invoke('instances:import', o),
  serverPing: (host) => ipcRenderer.invoke('server:ping', host),
  modsSearch: (o) => ipcRenderer.invoke('mods:search', o),
  modsDownload: (o) => ipcRenderer.invoke('mods:download', o),
  modsInstalled: (instanceId) => ipcRenderer.invoke('mods:listInstalled', instanceId),
  modsDelete: (filename, instanceId) => ipcRenderer.invoke('mods:delete', filename, instanceId),
  modpacksSearch: (o) => ipcRenderer.invoke('modpacks:search', o),
  modpacksInstall: (o) => ipcRenderer.invoke('modpacks:install', o),
  modpacksImport: () => ipcRenderer.invoke('modpacks:import'),
  onPackProgress: (cb) => ipcRenderer.on('modpacks:progress', (_e, p) => cb(p)),
  appVersion: () => ipcRenderer.invoke('app:version'),
  updateCheck: () => ipcRenderer.invoke('update:check'),
  updateInstall: (o) => ipcRenderer.invoke('update:install', o),
  onUpdateProgress: (cb) => ipcRenderer.on('update:progress', (_e, p) => cb(p)),
  serversSync: (servers) => ipcRenderer.invoke('servers:sync', servers),
  installLoader: (o) => ipcRenderer.invoke('loader:install', o),
  onLoaderStatus: (cb) => ipcRenderer.on('loader:status', (_e, p) => cb(p)),
  onModsProgress: (cb) => ipcRenderer.on('mods:progress', (_e, p) => cb(p)),
  onStatus: (cb) => ipcRenderer.on('game:status', (_e, p) => cb(p)),
  onLog: (cb) => ipcRenderer.on('game:log', (_e, t) => cb(t)),
  onExit: (cb) => ipcRenderer.on('game:exit', (_e, p) => cb(p)),
});
